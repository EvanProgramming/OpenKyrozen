"""Feature-owned durable task storage boundary."""
from typing import Protocol, Any

class TaskStore(Protocol):
    def write_task(self, task: dict, *, user_id: str, workspace_id: str, session_id: str | None) -> None: ...
    def claim_task(self, *, user_id: str, workspace_id: str, session_id: str | None) -> dict | None: ...
    def replace_tasks(self, tasks: list[dict], **scope) -> None: ...
    def list_tasks(self, **scope) -> list[dict]: ...
    def get_working_plan(self, **scope) -> dict | None: ...
    def set_working_plan_status(self, plan_id: str, status: str, **scope) -> bool: ...
    def list_working_plan_tasks(self, plan_id: str, **scope) -> list[dict]: ...
    def write_working_plan(self, plan: dict, tasks: list[dict], **scope) -> None: ...
    def apply_working_plan_edit(self, plan: dict, tasks: list[dict], **scope) -> int: ...
    def append_event(self, event_type: str, payload: Any, **scope) -> str: ...
